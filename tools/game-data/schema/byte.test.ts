import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { Effect, Schema } from "effect";
import { scalarTypes } from "./mappings/scalars.ts";
import { generate } from "./generate.ts";
import { parseFragment } from "./xml-codecs.ts";
import { FragmentXmlSchema } from "./tests/fixtures/byte.generated.ts";

const codec = scalarTypes["System.Byte"].codec;
const decode = Schema.decodeSync(codec);
const encode = Schema.encodeSync(codec);

test("Byte accepts decimal integers throughout its unsigned range", () => {
	for (const value of [0, 1, 127, 128, 254, 255]) {
		assert.equal(decode(String(value)), value);
		assert.equal(encode(value), String(value));
	}
	assert.equal(decode("+00255"), 255);
	assert.equal(decode("0000"), 0);
});

test("Byte rejects invalid XML numbers and out-of-range edits", () => {
	for (const text of [
		"-1",
		"256",
		"999999999999999999999",
		"1.5",
		"1e2",
		"0xff",
		"NaN",
		"Infinity",
		"",
		" ",
		"1_0",
	])
		assert.throws(() => decode(text), text);
	for (const value of [-1, 256, 1.5, NaN, Infinity, -Infinity])
		assert.throws(() => encode(value), String(value));
});

test("generated Byte fields preserve spelling and unknown XML during edits", async () => {
	const xml =
		'<Color B="000"><A>00255</A><R>00127</R><G>0</G><Palette><unsignedByte flag="keep">0001</unsignedByte><future>keep</future></Palette><!-- keep --></Color>';
	const read = Schema.decodeEffect(FragmentXmlSchema);
	const write = Schema.encodeEffect(FragmentXmlSchema);
	const color = await Effect.runPromise(read(xml));
	const alpha: number = color.value.A;
	const palette: readonly number[] = color.value.Palette;
	assert.equal(alpha, 255);
	assert.deepEqual(palette, [1]);
	const output = await Effect.runPromise(write(color));
	assert.deepEqual(
		await Effect.runPromise(parseFragment(output)),
		await Effect.runPromise(parseFragment(xml)),
	);
	const edited = await Effect.runPromise(
		write({ ...color, value: { ...color.value, A: 128, Palette: [255, 0] } }),
	);
	assert.match(edited, /<A>128<\/A><R>00127<\/R>/);
	assert.match(
		edited,
		/<unsignedByte flag="keep">255<\/unsignedByte><unsignedByte>0<\/unsignedByte><future>keep<\/future>/,
	);
	assert.match(edited, /B="000"/);
	await assert.rejects(
		Effect.runPromise(write({ ...color, value: { ...color.value, A: 256 } })),
	);
});

test("Byte scalar support does not silently reinterpret binary byte arrays", async () => {
	const catalog = JSON.parse(
		await readFile(
			new URL("./tests/fixtures/byte.catalog.json", import.meta.url),
			"utf8",
		),
	);
	catalog.types[0].members[0].type = "System.Byte[]";
	catalog.types.push({
		id: "System.Byte[]",
		kind: "collection",
		elementType: "System.Byte",
	});
	assert.throws(
		() => generate(catalog, "Example.Color"),
		/Example.Color.A: binary byte arrays are unsupported/,
	);
});
