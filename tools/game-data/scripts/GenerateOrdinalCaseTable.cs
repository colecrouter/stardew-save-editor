using System;
using System.Collections.Generic;
using System.Text;

// Run with the .NET 10 SDK from the repository root:
// dotnet run --file tools/game-data/scripts/GenerateOrdinalCaseTable.cs
// Redirect stdout to src/lib/save-format/ordinal-case-table.ts, then run Oxfmt on that file.
// Keep the captured table checked in: JavaScript and the host .NET runtime may
// use different Unicode versions, so JS casing is not a stable substitute.
var mappings = new List<(int CodePoint, int Delta)>();
for (var codePoint = 0; codePoint <= 0x10FFFF; codePoint++)
{
	if (!Rune.IsValid(codePoint)) continue;
	var rune = new Rune(codePoint);
	var upper = Rune.ToUpperInvariant(rune);
	// OrdinalIgnoreCase excludes some invariant-uppercase pairs, such as long S
	// versus ASCII S. Capture the actual comparer, not just uppercase conversion.
	if (rune != upper && StringComparer.OrdinalIgnoreCase.Equals(rune.ToString(), upper.ToString()))
		mappings.Add((codePoint, upper.Value - codePoint));
}

Console.WriteLine("// Generated by scripts/GenerateOrdinalCaseTable.cs; do not edit by hand.");
Console.WriteLine("// Each sorted range is [first code point, last code point, stride, uppercase delta].");
Console.WriteLine("// Unlisted code points are unchanged by this captured .NET OrdinalIgnoreCase policy.");
Console.WriteLine("export const ordinalCaseRanges: readonly (readonly [number, number, number, number])[] = [");
for (var index = 0; index < mappings.Count;)
{
	var (first, delta) = mappings[index];
	var last = first;
	// Alternating upper/lower alphabets form stride-two ranges; isolated mappings
	// remain singletons. Ranges must stay disjoint for runtime binary search.
	var stride = index + 1 < mappings.Count && mappings[index + 1].Delta == delta
		? mappings[index + 1].CodePoint - first : 1;
	if (stride > 2) stride = 1;
	var next = index + 1;
	while (next < mappings.Count && mappings[next].Delta == delta && mappings[next].CodePoint == last + stride)
	{
		last = mappings[next].CodePoint;
		next++;
	}
	Console.WriteLine($"\t[0x{first:X}, 0x{last:X}, {stride}, {delta}],");
	index = next;
}
Console.WriteLine("];");
