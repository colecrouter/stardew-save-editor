import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
	mkdir,
	mkdtemp,
	readdir,
	readFile,
	rm,
	writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { test } from "node:test";
import { pathToFileURL } from "node:url";

import { Schema } from "effect";

import { isRecord } from "../../../src/lib/unknown.ts";

const cli = resolve("tools/game-data/bin/Debug/net10.0/GameData.dll");
const fixtures = resolve("tools/game-data/tests/fixtures");
const run = (...args: string[]) =>
	spawnSync("dotnet", [cli, ...args], { encoding: "utf8" });

void test("coverage consumes the same resolved contract as generation", () => {
	// The descriptive command name and its compatibility alias must report the
	// same coverage, so existing automation can migrate without a behavior change.
	for (const command of ["coverage", "validate"]) {
		const result = run(
			command,
			"--catalog",
			join(fixtures, "fixture.catalog.json"),
			"--save",
			join(fixtures, "fixture.xml"),
		);
		assert.equal(result.status, 0, result.stderr);
		// Validate the CLI report envelope before comparing its coverage results.
		const report = Schema.decodeUnknownSync(
			Schema.Struct({
				files: Schema.Array(
					Schema.Struct({
						issues: Schema.Array(Schema.Unknown),
						unchecked: Schema.Array(Schema.Unknown),
						matchedElements: Schema.Finite,
					}),
				),
			}),
		)(JSON.parse(result.stdout));
		assert.deepEqual(report.files[0]?.issues, []);
		assert.deepEqual(report.files[0]?.unchecked, []);
		assert.ok((report.files[0]?.matchedElements ?? 0) > 0);
	}
});

void test("generation reports invalid contracts without replacing an existing module", async () => {
	const directory = await mkdtemp(join(tmpdir(), "game-data-"));
	try {
		const input = join(directory, "catalog.json"),
			output = join(directory, "generated.ts");
		const base = {
			formatVersion: 3,
			diagnostics: [],
			types: [{ id: "Example.Root", kind: "object", members: [] }],
		};
		// Each corruption would otherwise silently narrow or ambiguously interpret
		// the codec. The CLI must fail before publishing output in every case.
		for (const catalog of [
			{ ...base, formatVersion: 2 },
			{ ...base, diagnostics: ["loader failure"] },
			{ ...base, types: [...base.types, ...base.types] },
			{
				...base,
				types: [
					{
						...base.types[0],
						members: [{ name: "Future", type: "Unsupported.Type" }],
					},
				],
			},
		]) {
			await writeFile(input, JSON.stringify(catalog));
			await writeFile(output, "keep existing output");
			const result = run(
				"generate",
				"--catalog",
				input,
				"--type",
				"Example.Root",
				"--output",
				output,
			);
			assert.equal(result.status, 1);
			assert.notEqual(result.stderr.trim(), "");
			assert.equal(await readFile(output, "utf8"), "keep existing output");
		}
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});

void test("generation writes namespace modules that work together", async () => {
	// Generated modules import the "effect" package, which only resolves inside
	// the repository, so they go in the ignored .vitest directory, not the OS temp.
	await mkdir(resolve(".vitest"), { recursive: true });
	const directory = await mkdtemp(resolve(".vitest", "game-data-split-"));
	try {
		// Two namespaces that refer to each other in a cycle (Root -> Leaf -> Root)
		// and across inheritance (B.Dog derives from A.Animal), so the modules must
		// import each other and dispatch to a subclass declared in another module.
		const xmlInclude = (type: string) => ({
			type: "System.Xml.Serialization.XmlIncludeAttribute",
			constructorArguments: [{ type: "System.Type", value: type }],
		});
		const catalog = {
			formatVersion: 3,
			diagnostics: [],
			types: [
				{
					id: "A.Root",
					kind: "object",
					members: [
						{ name: "Name", type: "System.String" },
						{ name: "Child", type: "B.Leaf" },
						{ name: "Pet", type: "A.Animal" },
					],
				},
				{
					id: "A.Animal",
					kind: "object",
					members: [{ name: "Name", type: "System.String" }],
					attributes: [xmlInclude("B.Dog")],
				},
				{
					id: "B.Leaf",
					kind: "object",
					members: [
						{ name: "Label", type: "System.String" },
						{ name: "Back", type: "A.Root" },
					],
				},
				{
					id: "B.Dog",
					kind: "object",
					baseType: "A.Animal",
					members: [
						{ name: "Name", type: "System.String" },
						{ name: "Barks", type: "System.Int32" },
					],
				},
			],
		};
		const input = join(directory, "catalog.json");
		await writeFile(input, JSON.stringify(catalog));
		// A module left by an earlier run for a namespace that no longer exists
		// must be removed; a file the generator did not write must be kept.
		await mkdir(join(directory, "save"));
		await writeFile(
			join(directory, "save", "Removed.Namespace.ts"),
			"// Generated by game-data. Edit the catalog/compiler, not this file.\n",
		);
		await writeFile(join(directory, "save", "notes.ts"), "// hand-written\n");
		const result = run(
			"generate",
			"--catalog",
			input,
			"--type",
			"A.Root",
			"--runtime",
			resolve("src/lib/save-format/index.ts"),
			"--output",
			join(directory, "save.ts"),
		);
		assert.equal(result.status, 0, result.stderr);
		assert.deepEqual((await readdir(join(directory, "save"))).sort(), [
			"A.ts",
			"B.ts",
			"notes.ts",
		]);
		// Load the entry module's document schema, checking at runtime that it is
		// one. The modules are generated at test time, so TypeScript cannot see
		// their types; a generated document schema maps XML text to a value and
		// needs no Effect services, which is the type asserted here.
		const loaded: unknown = await import(
			pathToFileURL(join(directory, "save.ts")).href
		);
		assert.ok(isRecord(loaded) && Schema.isSchema(loaded["XmlSchema"]));
		// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- Checked by isSchema above; generated document schemas decode XML text without services.
		const document = loaded["XmlSchema"] as Schema.Codec<unknown, string>;
		const xml =
			'<Root xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"><Name>outer</Name>' +
			"<Child><Label>leaf</Label><Back><Name>inner</Name></Back></Child>" +
			'<Pet xsi:type="Dog"><Name>Rex</Name><Barks>3</Barks></Pet></Root>';
		// Decoding crosses both module boundaries: A.Root -> B.Leaf -> A.Root, and
		// A.Animal dispatches to B.Dog. The value must survive a round trip.
		const value = Schema.decodeSync(document)(xml);
		assert.ok(isRecord(value) && isRecord(value["Pet"]));
		assert.equal(value["Pet"]["$type"], "B.Dog");
		assert.equal(value["Pet"]["Barks"], 3);
		const encoded = Schema.encodeUnknownSync(document)(value);
		assert.deepEqual(Schema.decodeSync(document)(encoded), value);
		assert.match(encoded, /<Back><Name>inner<\/Name><\/Back>/);
		assert.match(encoded, /xsi:type="Dog"/);
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});
